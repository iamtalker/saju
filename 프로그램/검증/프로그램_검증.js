const assert=require('node:assert/strict');
const {calculate}=require('../engine');
const base={calendar:'solar',dayBoundary:'23'};
const run=(date,time,extra={})=>calculate({...base,year:date[0],month:date[1],day:date[2],time,...extra});
let r=run([2023,5,20],'12:00');
assert.equal(r.lunar,'2023년 4월 1일');
assert.equal(r.pillars[2].hanja,'戊寅');
const before=run([2025,2,3],'22:50'),after=run([2025,2,3],'23:30');
assert.deepEqual(before.pillars.slice(0,2).map(p=>p.hanja),['甲辰','丁丑']);
assert.deepEqual(after.pillars.slice(0,2).map(p=>p.hanja),['乙巳','戊寅']);
assert.equal(after.pillars[2].hanja,'甲辰');
assert.equal(run([2025,2,3],'23:30',{dayBoundary:'00'}).pillars[2].hanja,'癸卯');
assert.deepEqual(run([2025,2,3],'12:00',{unknown:true}).pillars,[null,null,null,null]);
assert.equal(run([2025,7,25],'12:00').lunar,'2025년 윤6월 1일');
assert.equal(run([2025,6,1],'12:00',{calendar:'lunar',leap:true}).solar,'2025년 7월 25일');
assert.throws(()=>run([2025,1,1],'12:00',{calendar:'lunar',leap:true}),/윤달/);
assert.equal(run([1988,7,15],'10:30').standardTime,'1988-07-15 09:30');
const reference=run([1992,11,28],'23:00',{correction:37});
assert.equal(reference.adjustedTime,'1992-11-28 22:23');
assert.deepEqual(reference.pillars.map(p=>p.hanja),['壬申','辛亥','戊申','癸亥']);
assert.deepEqual(run([1992,11,28],'23:00',{correction:30}).pillars.map(p=>p.hanja),['壬申','辛亥','戊申','癸亥']);
assert.throws(()=>run([1988,5,8],'02:30'),/존재하지 않는/);
assert.throws(()=>run([1988,10,9],'02:30'),/두 번/);
